# Đo tại minsup trung bình của từng bộ (results/minsup_grid.csv). Mỗi lần đo một tiến trình mới,
# có warm-up, ghi output ra file như mọi thí nghiệm khác; bộ đếm chạy riêng (không tính giờ).
# --level median (mặc định): đo tại minsup giữa của lưới, như E4. --level low: đo tại minsup THẤP NHẤT của lưới
# (khối lượng tính lớn nhất, nên thời gian đo ít bị nhiễu bởi chi phí cố định như ghi file).
# Kết quả: results/e8_ablation<hậu tố>.csv, e8_counters<hậu tố>.csv, e8_B03<hậu tố>.md, e8_B04<hậu tố>.md
# với hậu tố rỗng cho --level median và "_low" cho --level low.

using EclatFIM, Statistics, Printf   # EclatFIM: VARIANTS, VARIANT_NAMES; Statistics: median; Printf: định dạng bảng
include(joinpath(@__DIR__, "config_a.jl"))   # cấu hình của A: lưới minsup, DATASETS, append_csv, log_run
include(joinpath(@__DIR__, "bench_common.jl"))   # hàm đo trong tiến trình mới: run_ours, measure_ours!

const STATS_FIELDS = ["n_itemsets", "n_intersections", "n_failed", "n_skipped_pairs", "n_classes",   # các bộ đếm EclatStats ghi vào e8_counters*.csv
                      "n_switch", "max_depth", "bytes_peak", "time_level2_ns"]   # (tiếp)

"""Đọc CSV đơn giản (không có dấu phẩy trong ô) thành vector các Dict."""
function read_csv(path)   # đọc CSV đơn giản (không có dấu phẩy trong ô)
    lines = collect(eachline(path))   # mọi dòng của file
    header = split(lines[1], ",")   # dòng đầu là tên cột
    return [Dict(zip(header, split(l, ","))) for l in lines[2:end] if !isempty(strip(l))]   # mỗi dòng → Dict tên cột → giá trị
end

const VERSION_DESC = Dict(   # mô tả ngắn từng phiên bản cho cột Change của bảng B03
    "v0" => "baseline: vector tidsets, new allocation per intersection, lexical order",   # v0
    "v1" => "+ items ordered by ascending support",   # v1: trường order
    "v2" => "+ per-depth buffer reuse (no allocation in the hot loop)",   # v2: trường reuse
    "v3" => "+ adaptive intersection (early termination, galloping)",   # v3: trường isect
    "v4" => "+ bitset tidsets (BitVector)",   # v4: trường tidset = :bitset
    "v5" => "+ triangular array for 2-itemsets",   # v5: trường level2
    "v6" => "+ hybrid bitset → vector representation")   # v6: trường tidset = :hybrid

"""Mức minsup được đo cho một bộ: giữa lưới (median) hoặc thấp nhất (low)."""
pick_level(levels, level) = level == "low" ? levels[end] : median_minsup(levels)   # low: mức cuối (thấp nhất) của lưới; median: mức thứ 4
suffix(level) = level == "low" ? "_low" : ""     # hậu tố tên file kết quả

function write_tables(datasets, grid, level)   # sinh bảng B03 (thời gian) và B04 (bộ đếm) dạng Markdown
    rows = read_csv(joinpath(RES, "e8_ablation$(suffix(level)).csv"))   # mọi lần đo thời gian
    med = Dict{Tuple{String,String},Float64}()   # (bộ, phiên bản) → thời gian trung vị
    for ds in datasets, v in VARIANT_NAMES   # mọi bộ × mọi phiên bản
        ts = [parse(Float64, r["t_algo_s"]) for r in rows if r["dataset"] == ds && r["variant"] == v && r["status"] == "ok"]   # các lần đo thành công
        med[(ds, v)] = isempty(ts) ? NaN : median(ts)   # trung vị: ít bị ảnh hưởng bởi một lần đo bất thường hơn trung bình
    end
    io = IOBuffer()   # bộ đệm chuỗi cho bảng
    println(io, "# B03: ablation v0 → v6 (mining + writing time, median of repeated runs)\n")   # tiêu đề bảng B03
    println(io, "At the ", level == "low" ? "lowest" : "median", " minsup of each dataset. In parentheses: speedup over v0. Generated by `scripts/bench_ablation.jl --level ", level, "`.\n")   # ghi rõ mức minsup và lệnh sinh bảng
    println(io, "| Variant | Change | ", join(["$ds ($(pick_level(grid[ds], level)))" for ds in datasets], " | "), " |")   # hàng tiêu đề: tên bộ kèm minsup
    println(io, "|---|---|", repeat("---|", length(datasets)))   # đường kẻ Markdown
    for v in VARIANT_NAMES   # 7 phiên bản theo đúng thứ tự v0 → v6
        cells = String[]   # các ô của một hàng
        for ds in datasets   # từng bộ dữ liệu
            t, t0 = med[(ds, v)], med[(ds, "v0")]   # thời gian của phiên bản v và của v0
            push!(cells, isnan(t) ? "timeout" : @sprintf("%.3f s (×%.1f)", t, t0 / t))   # thời gian và tăng tốc so với v0
        end
        println(io, "| ", v, " | ", VERSION_DESC[v], " | ", join(cells, " | "), " |")   # một hàng của bảng
    end
    write(joinpath(RES, "e8_B03$(suffix(level)).md"), String(take!(io)))   # lưu bảng B03

    srows = read_csv(joinpath(RES, "e8_counters$(suffix(level)).csv"))   # bộ đếm của từng phiên bản
    io = IOBuffer()   # bộ đệm chuỗi cho bảng
    println(io, "# B04: internal counters per variant (one counter run, not timed)\n")   # tiêu đề bảng B04
    for ds in datasets   # từng bộ dữ liệu
        println(io, "## ", ds, " (minsup ", pick_level(grid[ds], level), ")\n")   # một mục cho mỗi bộ
        println(io, "| Variant | Itemsets | Intersections | Below threshold | Level-2 pairs skipped (triangular) | Level-2 time | Peak tidset | Bitset → vector switches |")   # tiêu đề cột B04
        println(io, "|---|---|---|---|---|---|---|---|")   # đường kẻ
        for r in srows   # mỗi dòng bộ đếm
            r["dataset"] == ds || continue   # chỉ lấy dòng của bộ đang viết
            @printf(io, "| %s | %s | %s | %s | %s | %.1f ms | %.2f MiB | %s |\n", r["variant"], r["n_itemsets"],   # một hàng B04
                    r["n_intersections"], r["n_failed"], r["n_skipped_pairs"], parse(Float64, r["time_level2_ns"]) / 1e6,   # ns → ms
                    parse(Float64, r["bytes_peak"]) / 2^20, r["n_switch"])   # byte → MiB
        end
        println(io)   # dòng trống giữa các bộ
    end
    write(joinpath(RES, "e8_B04$(suffix(level)).md"), String(take!(io)))   # lưu bảng B04
    println(read(joinpath(RES, "e8_B03$(suffix(level)).md"), String))   # in bảng B03 ra màn hình
end

# [VẤN ĐÁP] E8 — nghiên cứu loại bỏ (ablation study)
# LÀM GÌ    : đo 7 phiên bản tại một mức minsup của mỗi bộ; mỗi lần đo là một tiến trình Julia mới (run_one.jl).
# VÌ SAO    : hai phiên bản liền nhau khác đúng một kỹ thuật → chênh lệch là đóng góp riêng của kỹ thuật đó.
#             Tiến trình mới + khởi động trên dữ liệu toy: mọi phiên bản cùng điều kiện, không lẫn thời gian biên dịch JIT.
# BẰNG CHỨNG: minsup thấp nhất: bản nhanh nhất nhanh hơn v0 36–65 lần; v4 thắng chess, mushroom; v5 thắng retail, T10I4D100K.
# HỎI–ĐÁP   : H: Vì sao đo cả minsup giữa và thấp nhất? Đ: ở minsup giữa nhiều lần chạy chỉ vài ms, sai số tương đối lớn;
#             ở minsup thấp nhất khối lượng lớn nên số đo ổn định hơn. Hai mức cho cùng kết luận về từng kỹ thuật.
#             H: Máy đo khác Chương 2 có sao không? Đ: báo cáo chỉ so sánh các số đo trên CÙNG một máy (ghi ở ENV_A.md).
function main(args)   # đọc tham số dòng lệnh, đo, rồi sinh bảng
    k = findfirst(==("--repeats"), args)   # tùy chọn --repeats N
    repeats = k === nothing ? REPEATS : parse(Int, args[k+1])   # mặc định 3 lần
    k = findfirst(==("--datasets"), args)   # tùy chọn --datasets a,b
    grid = load_grid()   # lưới minsup của Chương 2 (results/minsup_grid.csv)
    datasets = k === nothing ? [d[1] for d in DATASETS] : String.(split(args[k+1], ","))   # mặc định 4 bộ benchmark
    datasets = [d for d in datasets if isfile(dataset_path(d)) && haskey(grid, d)]   # bỏ bộ chưa tải dữ liệu hoặc chưa có lưới
    k = findfirst(==("--level"), args)   # tùy chọn --level median|low
    level = k === nothing ? "median" : args[k+1]     # "median" hoặc "low"
    level in ("median", "low") || error("--level phải là median hoặc low")   # báo lỗi rõ ràng nếu gõ sai
    "--tables-only" in args && return write_tables(datasets, grid, level)   # chỉ sinh lại bảng từ CSV đã có, không đo
    path = joinpath(RES, "e8_ablation$(suffix(level)).csv")   # CSV thời gian
    spath = joinpath(RES, "e8_counters$(suffix(level)).csv")   # CSV bộ đếm
    for p in (path, spath)                     # đo lại từ đầu: không trộn với số liệu của lần chạy trước
        isfile(p) && rm(p)   # xóa kết quả cũ
    end
    for ds in datasets   # từng bộ dữ liệu
        ms = pick_level(grid[ds], level)   # mức minsup đo cho bộ này
        for v in VARIANT_NAMES   # 7 phiên bản theo đúng thứ tự v0 → v6
            # lặp 3 lần, hoặc 5 lần nếu một lần chạy dưới 1 giây (giao thức đo, như E2)
            r = measure_ours!(path, "E8", ds, dataset_path(ds), ms, v, repeats)
            println("  E8 $ds $ms $v: ", r["status"] == "ok" ? r["t_mine"] * " s" : r["status"])   # in tiến độ
            s = run_ours(dataset_path(ds), ms, v; out = "NUL", stats = true)   # lần chạy RIÊNG có bộ đếm, không tính giờ (D20)
            if s["status"] == "ok"   # chỉ ghi khi lần chạy thành công
                append_csv(spath, vcat(["dataset", "minsup", "variant"], STATS_FIELDS),   # ghi một dòng bộ đếm
                           vcat([ds, ms, v], [s[f] for f in STATS_FIELDS]))   # (tiếp)
            end
        end
    end
    write_tables(datasets, grid, level)   # sinh bảng B03, B04
end

let t0 = time()   # đo tổng thời gian chạy script
    main(ARGS)   # chạy với tham số dòng lệnh
    log_run("scripts/bench_ablation.jl", ARGS, time() - t0)   # ghi một dòng vào results/LOG.md
end
