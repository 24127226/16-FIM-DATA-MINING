# E10: bộ nhớ tidset theo tiến trình duyệt (phần của A). Kiểm chứng giả thuyết H7 (bài báo §7, Fig. 22):
# đỉnh bộ nhớ xuất hiện lúc dựng tidset các tập 2 item ở đầu mỗi lớp của lớp gốc, sau đó giảm dần
# vì tidset ngắn lại khi đi sâu (bổ đề 6). Bài báo đo trên dữ liệu tổng hợp thưa (T20.I6.D100K), nên
# nhóm đo trên cả một bộ dày (Chess) lẫn một bộ thưa cùng họ dữ liệu tổng hợp IBM (T10I4D100K).
#
#   julia --project=. scripts/bench_memory_trace.jl [bộ dữ liệu ...]     (mặc định: chess T10I4D100K)
#
# Mỗi bộ đo tại minsup trung bình của nó (results/minsup_grid.csv). Ghi số byte tidset đang sống sau mỗi
# tập phổ biến được xuất (lấy mẫu tối đa 4.000 điểm), kèm độ sâu của tập, cho bản vector (v3) và bản
# bitset (v4). Kết quả: results/e10_memory_trace.csv và bảng tóm tắt results/e10_memory_trace.md.

using EclatFIM, Printf   # EclatFIM: eclat!, EclatStats; Printf: định dạng bảng
include(joinpath(@__DIR__, "config_a.jl"))   # cấu hình của A

const HEADER = ["dataset", "minsup", "variant", "itemset_index", "bytes_current", "depth"]   # cột của e10_memory_trace.csv

function trace(path, ds, ms)   # ghi lại bộ nhớ tidset sau mỗi tập được xuất, cho v3 và v4
    db = read_spmf(dataset_path(ds))   # đọc bộ dữ liệu
    σ = minsup_count(parse_minsup(ms), n_transactions(db))   # minsup → số đếm
    summary = []   # tóm tắt từng phiên bản cho bảng
    for v in ("v3", "v4")   # danh sách tid (v3) và dãy bit (v4)
        st = EclatStats()   # bộ đếm: bytes_current là số byte tidset đang sống
        total = Ref(0)   # đếm tổng số tập (Ref: biến thay đổi được bên trong hàm vô danh)
        eclat!((i, s) -> (total[] += 1), db, σ, VARIANTS[v])                 # đếm trước số tập
        step = max(1, total[] ÷ 4000)   # lấy mẫu tối đa 4.000 điểm để file CSV gọn
        rows = Tuple{Int,Int,Int}[]   # (thứ tự tập, byte đang sống, độ dài tập)
        k = Ref(0)   # thứ tự của tập đang xuất
        eclat!(db, σ, VARIANTS[v]; stats = st) do items, s   # chạy lại, lần này có bộ đếm; khối do ... end là sink
            k[] += 1   # thêm một tập
            k[] % step == 0 && push!(rows, (k[], st.bytes_current, length(items)))   # ghi điểm mẫu: bộ nhớ ngay lúc tập này được xuất
        end
        for (i, b, d) in rows   # ghi các điểm mẫu ra CSV
            append_csv(path, HEADER, [ds, ms, v, i, b, d])   # một dòng CSV
        end
        bytes = [b for (_, b, _) in rows]   # dãy giá trị bộ nhớ
        ipk = argmax(bytes)   # vị trí điểm mẫu có bộ nhớ lớn nhất
        mean = sum(bytes) / length(bytes)   # bộ nhớ trung bình
        push!(summary, (v = v, n = total[], peak = st.bytes_peak, at = rows[ipk][1], depth = rows[ipk][3],   # lưu tóm tắt
                        mean = mean, maxlen = st.max_depth))   # (tiếp)
        println(ds, " ", ms, " ", v, ": ", total[], " tập, tidset đỉnh ", round(st.bytes_peak / 2^20; digits = 3),   # in tiến độ
                " MiB tại tập thứ ", rows[ipk][1], " (độ dài ", rows[ipk][3], ")")   # (tiếp)
    end
    return summary   # trả tóm tắt cho main
end

# [VẤN ĐÁP] E10 — bộ nhớ tidset theo tiến trình duyệt
# BẰNG CHỨNG: đường bộ nhớ gần như phẳng: đỉnh / trung bình = 1,38–1,42 (chess), 1,00–1,01 (T10I4D100K).
#             Dãy bit giảm đỉnh 28 lần trên chess (0,731 → 0,026 MiB) nhưng tăng 48% trên T10I4D100K (3,05 → 4,51 MiB).
# HỎI–ĐÁP   : H: Bài báo nói đỉnh bộ nhớ ở đầu mỗi lớp (H7), sao nhóm không thấy? Đ: bài báo dựng xong MỌI lớp con rồi mới
#             đệ quy; cài đặt của nhóm đệ quy ngay, mỗi độ sâu chỉ giữ một lớp, nên không lúc nào giữ cùng lúc tidset mọi
#             tập 2 item của một lớp lớn. Trên T10I4D100K gần như toàn bộ bộ nhớ là tidset của lớp gốc.
function main(args)   # đo các bộ được chọn rồi viết bảng
    datasets = isempty(args) ? ["chess", "T10I4D100K"] : args   # mặc định: một bộ dày và một bộ thưa cùng họ IBM với bài báo
    grid = load_grid()   # lưới minsup của Chương 2
    path = joinpath(results_dir(), "e10_memory_trace.csv")   # file kết quả
    isfile(path) && rm(path)   # đo lại từ đầu
    io = IOBuffer()   # bộ đệm chuỗi
    println(io, "# E10: live tidset memory over the search (hypothesis H7)\n")   # tiêu đề
    println(io, "Generated by `scripts/bench_memory_trace.jl`. Peak from the internal counter; peak position and mean ",   # cách đọc bảng
            "over the sampled points (at most 4,000 per run).\n")   # (tiếp)
    println(io, "| Dataset | minsup | Variant | Itemsets | Peak tidset | Mean | Peak / mean | Peak at itemset # | Itemset length at peak | Longest itemset |")
    println(io, "|---|---|---|---|---|---|---|---|---|---|")   # đường kẻ
    for ds in datasets   # mỗi bộ
        ms = median_minsup(grid[ds])   # đo tại minsup giữa, như E4
        for s in trace(path, ds, ms)   # mỗi phiên bản
            @printf(io, "| %s | %s | %s | %d | %.3f MiB | %.3f MiB | %.2f | %d | %d | %d |\n", ds, ms, s.v, s.n,   # một hàng
                    s.peak / 2^20, s.mean / 2^20, s.peak / s.mean, s.at, s.depth, s.maxlen)   # đỉnh, trung bình, tỉ số, vị trí đỉnh
        end
    end
    write(joinpath(results_dir(), "e10_memory_trace.md"), String(take!(io)))   # lưu bảng
    println(read(joinpath(results_dir(), "e10_memory_trace.md"), String))   # in bảng
end

let t0 = time()   # đo tổng thời gian
    main(ARGS)   # chạy
    log_run("scripts/bench_memory_trace.jl", ARGS, time() - t0)   # ghi results/LOG.md
end
